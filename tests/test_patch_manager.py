from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from app.harness.patch_manager import PatchManager


class PatchManagerTests(unittest.TestCase):
    def test_ignores_task_virtualenv_when_building_diff(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            baseline = root / "baseline"
            workspace = root / "workspace"
            baseline.mkdir()
            workspace.mkdir()
            (baseline / "module.py").write_text("value = 1\n", encoding="utf-8")
            (workspace / "module.py").write_text("value = 2\n", encoding="utf-8")
            (workspace / ".patchforge_venv" / "lib").mkdir(parents=True)
            (workspace / ".patchforge_venv" / "lib" / "generated.py").write_text("noise\n", encoding="utf-8")

            diff = PatchManager(workspace, baseline).get_diff()

            self.assertIn("module.py", diff)
            self.assertNotIn(".patchforge_venv", diff)

    def test_ignores_vcs_versioning_generated_file(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            baseline = root / "baseline"
            workspace = root / "workspace"
            (baseline / "src" / "pkg").mkdir(parents=True)
            (workspace / "src" / "pkg").mkdir(parents=True)
            (baseline / "src" / "pkg" / "module.py").write_text("value = 1\n", encoding="utf-8")
            (workspace / "src" / "pkg" / "module.py").write_text("value = 2\n", encoding="utf-8")
            (workspace / "src" / "pkg" / "_version.py").write_text(
                "# file generated by vcs-versioning\n__version__ = '999.0.0'\n",
                encoding="utf-8",
            )

            diff = PatchManager(workspace, baseline).get_diff()

            self.assertIn("module.py", diff)
            self.assertNotIn("_version.py", diff)


if __name__ == "__main__":
    unittest.main()

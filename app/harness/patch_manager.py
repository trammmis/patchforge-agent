from __future__ import annotations

import difflib
import os
from pathlib import Path

from app.tools.path_guard import display_path

IGNORED_DIFF_PARTS = {".git", ".patchforge_venv", "__pycache__", ".pytest_cache"}


class PatchManager:
    def __init__(self, workspace: Path | str, baseline: Path | str) -> None:
        self.workspace = Path(workspace).resolve()
        self.baseline = Path(baseline).resolve()

    def get_diff(self) -> str:
        chunks: list[str] = []
        files = sorted(
            {
                *_iter_files(self.baseline),
                *_iter_files(self.workspace),
            }
        )
        for rel in files:
            if any(part in IGNORED_DIFF_PARTS for part in rel.parts):
                continue
            old_path = self.baseline / rel
            new_path = self.workspace / rel
            if _is_generated_runtime_artifact(old_path, new_path):
                continue
            old_text = old_path.read_text(encoding="utf-8", errors="ignore").splitlines() if old_path.exists() else []
            new_text = new_path.read_text(encoding="utf-8", errors="ignore").splitlines() if new_path.exists() else []
            if old_text == new_text:
                continue
            rel_display = str(rel).replace("\\", "/")
            chunks.extend(
                difflib.unified_diff(
                    old_text,
                    new_text,
                    fromfile=f"a/{rel_display}",
                    tofile=f"b/{rel_display}",
                    lineterm="",
                )
            )
        return "\n".join(chunks) + ("\n" if chunks else "")

    def modified_files(self) -> list[str]:
        diff = self.get_diff()
        return [line[6:] for line in diff.splitlines() if line.startswith("+++ b/")]


def _iter_files(root: Path) -> set[Path]:
    files: set[Path] = set()
    for current, dirs, names in os.walk(root):
        dirs[:] = [name for name in dirs if not _is_ignored_diff_part(name)]
        current_path = Path(current)
        for name in names:
            path = current_path / name
            try:
                rel = path.relative_to(root)
            except ValueError:
                continue
            if any(_is_ignored_diff_part(part) for part in rel.parts):
                continue
            try:
                if path.is_file():
                    files.add(rel)
            except OSError:
                continue
    return files


def _is_ignored_diff_part(part: str) -> bool:
    """Exclude VCS, runtime, and packaging metadata from the reviewable patch."""

    return part in IGNORED_DIFF_PARTS or part.endswith(".egg-info")


def _is_generated_runtime_artifact(old_path: Path, new_path: Path) -> bool:
    if old_path.exists() or not new_path.exists():
        return False
    try:
        head = new_path.read_text(encoding="utf-8", errors="ignore")[:300]
    except OSError:
        return False
    return "file generated by vcs-versioning" in head
